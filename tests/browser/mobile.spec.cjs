const { test, expect } = require('@playwright/test');
const fs = require('node:fs/promises');
const base = 'https://ychris12138.github.io/progress-dashboard/';
for (const width of [360, 390]) {
  test(`empty live site and local draft at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 844 });
    const errors = [], writes = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', req => { if (!['GET', 'HEAD'].includes(req.method())) writes.push(req.url()); });
    const response = await page.goto(base);
    expect(response.status()).toBe(200);
    await expect(page.locator('#projects')).toHaveAttribute('aria-busy', 'false');
    await expect(page.locator('#load-error')).toBeHidden();
    await expect(page.getByRole('heading', {name:'每一步，都有迹可循。'})).toBeVisible();
    const data = await (await page.request.get(base + 'data.json')).json();
    expect(data.projects).toEqual([]); expect(data.timeline).toEqual([]);
    const geometry = await page.evaluate(() => ({width:innerWidth, scrollWidth:document.documentElement.scrollWidth}));
    expect(geometry.width).toBe(width);
    expect(geometry.scrollWidth).toBeLessThanOrEqual(width);
    await page.screenshot({path:info.outputPath(`home-${width}.png`),fullPage:true});
    await page.locator('#tab-timeline').click();
    await expect(page.locator('#panel-timeline')).toBeVisible();
    await page.locator('#open-record').click();
    await expect(page.locator('#record-dialog')).toBeVisible();
    await page.locator('#mode-manual').click();
    await page.locator('#record-project').selectOption('__custom__');
    await page.locator('#custom-project').fill('proj_synthetic_mobile');
    await page.locator('#occurred-at').fill('2026-11-13');
    await page.locator('#summary').fill('合成手机验收记录，不发布');
    await page.locator('#evidence').fill('仅验证本地 JSON 下载');
    const dialog = await page.locator('#record-dialog').boundingBox();
    expect(dialog.x).toBeGreaterThanOrEqual(0);
    expect(dialog.x + dialog.width).toBeLessThanOrEqual(width + 1);
    const overflow = await page.locator('#record-dialog').evaluate(el => el.scrollWidth > el.clientWidth);
    expect(overflow).toBe(false);
    await page.screenshot({path:info.outputPath(`record-${width}.png`),fullPage:true});
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('button',{name:'下载 JSON 草稿',exact:true}).click();
    const download = await downloadPromise;
    await download.saveAs(info.outputPath('synthetic-draft.json'));
    const draft = JSON.parse(await page.locator('#draft-json').inputValue());
    expect(draft.verification).toBe('needs_review');
    expect(draft).not.toHaveProperty('record_id');
    expect(draft).not.toHaveProperty('recorded_at');
    expect(draft.occurred_at).toBe('2026-11-13');
    await page.getByRole('button',{name:'关闭记录进度',exact:true}).click();
    await expect(page.locator('#record-dialog')).toBeHidden();
    expect(errors).toEqual([]); expect(writes).toEqual([]);
    await fs.writeFile(info.outputPath('metrics.json'),JSON.stringify({width,geometry,dialog,errors,writes},null,2));
  });
}
